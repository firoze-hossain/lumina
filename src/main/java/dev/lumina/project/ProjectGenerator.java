    private static void generateMavenArchetype(ProjectSpec spec, Path dir, Consumer<String> log)
            throws IOException {
        Files.createDirectories(spec.location());

        String archetype = required(spec.archetypeId(), "maven-archetype-quickstart");
        int separator = archetype.indexOf(':');
        String archetypeGroupId = separator > 0
                ? archetype.substring(0, separator) : "org.apache.maven.archetypes";
        String archetypeId = separator > 0 ? archetype.substring(separator + 1) : archetype;
        String archetypeVersion = required(spec.archetypeVersion(), "1.4");
        String projectVersion = required(spec.projectVersion(), "1.0-SNAPSHOT");
        String catalog = switch (required(spec.archetypeCatalog(), "Internal")) {
            case "Default Local" -> "local";
            case "Maven Central" -> "remote";
            default -> "internal";
        };

        log.accept("Generating Maven project from " + archetypeId + " …");
        ProcessBuilder builder = new ProcessBuilder(
                "mvn", "archetype:generate", "-B",
                "-DarchetypeCatalog=" + catalog,
                "-DarchetypeGroupId=" + archetypeGroupId,
                "-DarchetypeArtifactId=" + archetypeId,
                "-DarchetypeVersion=" + archetypeVersion,
                "-DgroupId=" + spec.group(),
                "-DartifactId=" + spec.artifact(),
                "-Dversion=" + projectVersion,
                "-Dpackage=" + spec.packageName())
                .directory(spec.location().toFile())
                .redirectErrorStream(true);
        addAdditionalProperties(builder, spec.additionalProperties());

        Process process = builder.start();
        try (BufferedReader output = new BufferedReader(new InputStreamReader(
                process.getInputStream(), StandardCharsets.UTF_8))) {
            String line;
            while ((line = output.readLine()) != null) {
                log.accept(line);
            }
        }
        try {
            int exitCode = process.waitFor();
            if (exitCode != 0) {
                throw new IOException("Maven archetype generation failed with exit code " + exitCode);
            }
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IOException("Maven archetype generation interrupted", e);
        }

        if (!Files.isDirectory(dir)) {
            throw new IOException("Maven did not create the expected project directory: " + dir);
        }
    }

    private static void addAdditionalProperties(ProcessBuilder builder, String properties) {
        if (properties == null || properties.isBlank()) {
            return;
        }
        for (String property : properties.split("[\\r\\n,]+")) {
            String trimmed = property.trim();
            if (!trimmed.isBlank() && trimmed.contains("=")) {
                builder.command().add("-D" + trimmed);
            }
        }
    }

