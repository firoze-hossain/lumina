    private static void generateRust(ProjectSpec spec, Path dir, Consumer<String> log)
            throws IOException {
        Files.createDirectories(spec.location());
        String cargo = cargoExecutable(spec.rustToolchainPath());
        String template = required(spec.rustTemplate(), "Binary (application)");
        List<String> command = new java.util.ArrayList<>();
        command.add(cargo);
        if (template.startsWith("Custom:")) {
            String url = template.substring("Custom:".length()).trim();
            if (url.isBlank()) throw new IOException("Custom Rust template URL is required");
            command.addAll(List.of("generate", "--git", url, "--name", spec.name()));
            log.accept("Generating Rust project from " + url + " …");
        } else {
            command.add("new");
            command.add(template.startsWith("Library") ? "--lib" : "--bin");
            command.add(spec.name());
            log.accept("Generating Rust " + (template.startsWith("Library") ? "library" : "binary")
                    + " with Cargo …");
        }

        ProcessBuilder builder = new ProcessBuilder(command)
                .directory(spec.location().toFile())
                .redirectErrorStream(true);
        addEnvironment(builder, spec.rustEnvironment());
        runProcess(builder, "Rust project generation", log);
        if (!Files.isDirectory(dir)) {
            throw new IOException("Cargo did not create the expected project directory: " + dir);
        }
    }

    private static String cargoExecutable(String toolchainPath) {
        if (toolchainPath == null || toolchainPath.isBlank()) return "cargo";
        Path candidate = Path.of(toolchainPath).resolve("cargo");
        return Files.isExecutable(candidate) ? candidate.toString() : "cargo";
    }

    private static void addEnvironment(ProcessBuilder builder, String variables) {
        if (variables == null || variables.isBlank()) return;
        for (String variable : variables.split("[\\r\\n;]+")) {
            int separator = variable.indexOf('=');
            if (separator > 0) {
                builder.environment().put(variable.substring(0, separator).trim(),
                        variable.substring(separator + 1).trim());
            }
        }
    }

    private static void runProcess(ProcessBuilder builder, String operation, Consumer<String> log)
            throws IOException {
        Process process = builder.start();
        try (BufferedReader output = new BufferedReader(new InputStreamReader(
                process.getInputStream(), StandardCharsets.UTF_8))) {
            String line;
            while ((line = output.readLine()) != null) log.accept(line);
        }
        try {
            int exitCode = process.waitFor();
            if (exitCode != 0) throw new IOException(operation + " failed with exit code " + exitCode);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IOException(operation + " interrupted", e);
        }
    }

    private static void unzip(byte[] zipBytes, Path target) throws IOException {
        Path root = target.toAbsolutePath().normalize();
        String commonPrefix = null;
        boolean hasMultipleRoots = false;
        try (ZipInputStream zis = new ZipInputStream(new ByteArrayInputStream(zipBytes))) {
            ZipEntry entry;
            while ((entry = zis.getNextEntry()) != null) {
                String name = entry.getName();
                if (name.startsWith("/")) name = name.substring(1);
                int slash = name.indexOf('/');
                if (slash > 0) {
                    String prefix = name.substring(0, slash + 1);
                    if (commonPrefix == null) {
                        commonPrefix = prefix;
                    } else if (!name.startsWith(commonPrefix)) {
                        hasMultipleRoots = true;
                        break;
                    }
                } else if (!entry.isDirectory()) {
                    hasMultipleRoots = true;
                    break;
                }
                zis.closeEntry();
            }
        }
        if (hasMultipleRoots || commonPrefix == null) {
            commonPrefix = "";
        }

        try (ZipInputStream zis = new ZipInputStream(new ByteArrayInputStream(zipBytes))) {
            ZipEntry entry;
            while ((entry = zis.getNextEntry()) != null) {
                String name = entry.getName();
                if (name.startsWith("/")) name = name.substring(1);
                if (!commonPrefix.isEmpty() && name.startsWith(commonPrefix)) {
                    name = name.substring(commonPrefix.length());
                }
                if (name.isEmpty() || name.equals("/")) {
                    zis.closeEntry();
                    continue;
                }
                Path out = root.resolve(name).normalize();
                if (!out.startsWith(root)) {
                    throw new IOException("Blocked zip entry outside target: " + entry.getName());
                }
                if (entry.isDirectory()) {
                    Files.createDirectories(out);
                } else {
                    Files.createDirectories(out.getParent());
                    Files.copy(zis, out, java.nio.file.StandardCopyOption.REPLACE_EXISTING);
                }
                zis.closeEntry();
            }
        }
    }

